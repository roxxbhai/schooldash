import { z } from 'zod';
import { normalizeSubjectName } from '@/helpers/subjects';
import type { DbErrorContext } from '@/types/supabase';

export const SUBJECT_COLUMNS = 'id, code, name, description, createdAt, updatedAt';

export const SUBJECT_ERRORS: DbErrorContext = {
  notFoundMessage: 'Subject not found.',
  constraints: {
    subjects_code_key: { message: 'A subject with this code already exists.', field: 'code' },
    subjectsCodeNotBlank: { message: 'code is required.', field: 'code' },
    subjectsNameNotBlank: { message: 'name is required.', field: 'name' },
    subjectsNameKey: { message: 'A subject with this name already exists.', field: 'name' },
    subjectsNameFormat: { message: 'name may contain only letters, numbers and spaces.', field: 'name' },
  },
};

/** SAME RULE AS THE "subjectsNameFormat" CHECK: LETTERS AND DIGITS, SINGLE SPACES BETWEEN WORDS. */
export const SUBJECT_NAME_PATTERN = /^[A-Z0-9]+( [A-Z0-9]+)*$/;

/** STORED NORMALIZED (SEE normalizeSubjectName). SUBJECT CODES ARE GENERATED BY THE DB, NEVER SENT. */
export const SUBJECT_NAME_SCHEMA = z
  .string()
  .transform(normalizeSubjectName)
  .pipe(
    z
      .string()
      .min(1, 'name is required.')
      .max(100)
      .regex(SUBJECT_NAME_PATTERN, 'name may contain only letters, numbers and spaces.'),
  );
